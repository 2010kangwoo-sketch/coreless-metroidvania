export function validateResetPass01RoomPlan() {
  const prepass = validatePrepassProductionContract();
  const ids = RESET_PASS01_ROOMS.map(item => item.id);
  const tasks = RESET_PASS01_ROOMS.filter(item => item.task);
  const enemyIds = new Set(
    RESET_PASS01_ROOMS.flatMap(item =>
      item.enemies.filter(enemyId => ENEMY_ROLES[Object.keys(ENEMY_ROLES)
        .find(key => ENEMY_ROLES[key].id === enemyId)])),
  );
  const coreEnemyIds = new Set(Object.values(ENEMY_ROLES).map(item => item.id));
  const usedCoreEnemyIds = new Set(
    RESET_PASS01_ROOMS.flatMap(item =>
      item.enemies.filter(enemyId => coreEnemyIds.has(enemyId))),
  );
  const conversations = RESET_PASS01_ROOMS.filter(item =>
    item.radio?.kind === "conversation");
  const warnings = RESET_PASS01_ROOMS.filter(item =>
    item.radio?.kind === "warning");
  const checkpointIds = RESET_PASS01_ROOMS.filter(item => item.checkpoint)
    .map(item => item.id);
  const highIntensityRuns = [];
  let run = 0;
  RESET_PASS01_ROOMS.forEach(item => {
    run = item.intensity >= 4 ? run + 1 : 0;
    highIntensityRuns.push(run);
  });
  const checks = [
    ["prepassStillValid", prepass.passed],
    ["resetPassOne", RESET_PASS01_BUILD.pass === 1],
    ["thirtySixRooms", RESET_PASS01_ROOMS.length === 36],
    ["idsContiguous", ids.every((id, index) =>
      id === `S${String(index + 1).padStart(2, "0")}`)],
    ["sixTiers", RESET_PASS01_TIER_BUDGETS.length === 6],
    ["sixRoomsPerTier", RESET_PASS01_TIER_BUDGETS.every(item =>
      RESET_PASS01_ROOMS.filter(roomItem => roomItem.tier === item.tier).length === 6)],
    ["zigzagDirections", RESET_PASS01_TIER_BUDGETS.map(item =>
      item.direction).join(",") === "east,west,east,west,east,west"],
    ["columnsContiguousWithinTiers", RESET_PASS01_ROOMS.every((item, index) =>
      index === 0 ||
      item.tier !== RESET_PASS01_ROOMS[index - 1].tier ||
      Math.abs(item.column - RESET_PASS01_ROOMS[index - 1].column) === 1)],
    ["twelveMinuteBudget", RESET_PASS01_ROOMS.reduce((sum, item) =>
      sum + item.targetSeconds, 0) === 720],
    ["ordinaryRoomTiming", RESET_PASS01_ROOMS.every(item =>
      item.role === "boss" ||
      (item.targetSeconds >= 10 && item.targetSeconds <= 35))],
    ["bossPairTiming", RESET_PASS01_ROOMS
      .filter(item => item.role === "boss")
      .reduce((sum, item) => sum + item.targetSeconds, 0) >= 60],
    ["allRoomsHavePurpose", RESET_PASS01_ROOMS.every(item =>
      item.purpose.length >= 20)],
    ["allRoomsHaveDecision", RESET_PASS01_ROOMS.every(item =>
      item.decision.length >= 18)],
    ["allRoomsHaveRecovery", RESET_PASS01_ROOMS.every(item =>
      item.recovery.length >= 18)],
    ["allRoomsHaveStory", RESET_PASS01_ROOMS.every(item =>
      item.story.length >= 18)],
    ["allRoomsHaveSupportRule", RESET_PASS01_ROOMS.every(item =>
      item.supportRule.length >= 20)],
    ["terrainSignaturesUnique", new Set(RESET_PASS01_ROOMS.map(item =>
      item.terrainSignature)).size === 36],
    ["twentyThreeMandatoryTasks", tasks.length === 23],
    ["tasksCannotBeBypassed", tasks.every(item =>
      item.task.exitRule === "sealed-until-complete" &&
      !item.task.bypassAllowed)],
    ["tasksHaveReadableFeedback", tasks.every(item =>
      item.task.feedback.length >= 18)],
    ["combatAndBossRoomsGated", RESET_PASS01_ROOMS
      .filter(item => ["combat", "boss"].includes(item.role))
      .every(item => Boolean(item.task))],
    ["maximumThreeActiveEnemies", RESET_PASS01_ROOMS.every(item =>
      item.maximumActiveEnemies <= 3)],
    ["fiveCoreEnemyRolesUsed", usedCoreEnemyIds.size === 5],
    ["enemyRoleCatalogHasFiveEntries", enemyIds.size === 5],
    ["tutorialStartsWithoutEnemies", RESET_PASS01_ROOMS.slice(0, 8)
      .every(item => item.enemies.length === 0)],
    ["firstFourZonesAreRadioSilent", RESET_PASS01_ROOMS.slice(0, 4)
      .every(item => item.radio === null)],
    ["transceiverAcquiredAtS05", RESET_PASS01_ROOMS[4].radio?.kind ===
      "acquisition" && RESET_PASS01_ROOMS[4].id ===
      RADIO_CONTRACT.acquisition.cabinetZone],
    ["firstContactAtS06", RESET_PASS01_ROOMS[5].radio?.id ===
      "maren-first-contact" && RESET_PASS01_ROOMS[5].id ===
      RADIO_CONTRACT.acquisition.firstContactZone],
    ["threeCoreConversations", conversations.length === 3],
    ["twoHazardWarnings", warnings.length === 2],
    ["allDialogueIsNonBlockingAndSafe", RESET_PASS01_ROOMS
      .filter(item => item.radio)
      .every(item => !item.radio.blocksInput && item.radio.safe)],
    ["radioNeverRepeatsAfterDeath", RESET_PASS01_ROOMS
      .filter(item => item.radio)
      .every(item => !item.radio.repeatedAfterDeath)],
    ["dialogueLinesHaveKnownSpeakers", RESET_PASS01_ROOMS
      .flatMap(item => item.radio?.lines ?? [])
      .every(line => ["마렌", "코어리스"].includes(line.speaker))],
    ["checkpointCadence", checkpointIds.join(",") ===
      "S01,S06,S12,S18,S24,S30,S35"],
    ["noNewSkillGranted", RESET_PASS01_ROOMS.every(item =>
      !item.grantsNewAbility) &&
      PREPASS_APPROVAL_GATES.firstRoomAddsNewSkill === false],
    ["m02NamedAtExit", RESET_PASS01_ROOMS.at(-1).story.includes("냉각 수로")],
    ["highIntensityRunBounded", Math.max(...highIntensityRuns) <= 2],
    ["releaseScopeMatches", RELEASE_VERTICAL_SLICE.firstFortyPassScope
      .firstMegaRoomSpaces === RESET_PASS01_ROOMS.length],
  ].map(([name, passed]) => frozen({ name, passed: Boolean(passed) }));

  return frozen({
    passed: checks.every(item => item.passed),
    passedCount: checks.filter(item => item.passed).length,
    totalCount: checks.length,
    checks: frozen(checks),
    measurements: frozen({
      rooms: RESET_PASS01_ROOMS.length,
      tiers: RESET_PASS01_TIER_BUDGETS.length,
      totalSeconds: RESET_PASS01_ROOMS.reduce((sum, item) =>
        sum + item.targetSeconds, 0),
      mandatoryTasks: tasks.length,
      uniqueTerrainSignatures: new Set(RESET_PASS01_ROOMS.map(item =>
        item.terrainSignature)).size,
      coreEnemyRolesUsed: usedCoreEnemyIds.size,
      maximumActiveEnemies: Math.max(...RESET_PASS01_ROOMS.map(item =>
        item.maximumActiveEnemies)),
      conversations: conversations.length,
      warnings: warnings.length,
      checkpoints: checkpointIds.length,
    }),
  });
}

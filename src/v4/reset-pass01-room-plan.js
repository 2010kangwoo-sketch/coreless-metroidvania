const room = ({
  id,
  name,
  role,
  targetSeconds,
  intensity,
  extent,
  terrainSignature,
  purpose,
  decision,
  recovery,
  supportRule,
  interaction,
  story,
  roomTask = null,
  enemies = [],
  maximumActiveEnemies = 0,
  radioEvent = null,
  checkpoint = false,
}) => {
  const sequence = Number(id.slice(1));
  const tier = Math.floor((sequence - 1) / 6) + 1;
  const orderInTier = (sequence - 1) % 6 + 1;
  const direction = tier % 2 === 1 ? "east" : "west";
  const column = direction === "east" ? orderInTier : 7 - orderInTier;
  return frozen({
    id,
    sequence,
    tier,
    orderInTier,
    direction,
    column,
    name,
    role,
    targetSeconds,
    intensity,
    extent,
    terrainSignature,
    purpose,
    decision,
    recovery,
    supportRule,
    interaction,
    story,
    task: roomTask,
    enemies: frozen(enemies),
    maximumActiveEnemies,
    radio: radioEvent,
    checkpoint,
    entryReadability: "입구 측면 프레임과 직전 공간 재질 변화로 경계를 표시",
    exitReadability: roomTask
      ? "과제 문양·출구 조명·기계 반응으로 잠금과 해제를 표시"
      : "진행 방향의 공명 빛과 다음 공간 실루엣으로 출구를 표시",
    requiredAbilities: frozen([
      "move",
      "variable_jump",
      "air_control",
      ...(sequence >= 8 ? ["basic_attack"] : []),
      "interact",
    ]),
    grantsNewAbility: false,
  });
};

